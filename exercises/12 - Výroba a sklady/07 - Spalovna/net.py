from pn import Net

net = Net("Spalovna (půlsemestrálky 2014–19, Z15)")

# dovážka: auto každých 6 min (10 kubíků/h); místo ve skladu se zabere při vjezdu
net.place("gen", (0, 0), tokens=1, label="příchody aut", label_pos="above")
net.timed("prijezd", (1.5, 0), "6 min", param_pos="below")
net.loop("gen", "prijezd")
net.place("auto", (3, 0), label="auto", label_pos="above")
net.immediate("vjezd", (4.5, 0), p=1, param_pos="below")
net.place("volne", (4.5, 1.6), tokens=50, label="Volné místo ve skladu", label_pos="above")
net.place("vyklada", (6, 0))
net.timed("vylozeni", (7.5, 0), "2 min", param_pos="above")
net.chain("prijezd", "auto", "vjezd", "vyklada", "vylozeni")
net.arc("volne", "vjezd")
net.place("sklad", (9, 0), tokens=50, label="Sklad", label_pos="above")
net.arc("vylozeni", "sklad")

# auto odjíždí: vyložené, nebo hned nevyložené (sklad plný, p=0)
net.immediate("plno", (3, -1.6), label="sklad plný", label_pos="left")
net.arc("auto", "plno")
net.place("odjel", (7.5, -1.6), label="odjíždí", label_pos="below")
net.immediate("odjezd", (9, -1.6), exit=True, label="odchod", label_pos="below")
net.arc("plno", "odjel")
net.arc("vylozeni", "odjel")
net.arc("odjel", "odjezd")

# linka (1 kubík naráz) pod zahájením; rychlost se zvolí při zahájení: zrychlený režim p=1
net.place("linka", (10.5, -3.2), tokens=1, label="Linka", label_pos="below left")
net.immediate("zahajeni", (10.5, 0))
net.place("na_lince", (12, 0))
net.chain("sklad", "zahajeni", "na_lince")
net.arc("linka", "zahajeni")
net.arc("zahajeni", "volne", via=[(10.5, 1.6)])
net.immediate("normal", (15, 1.6))
net.immediate("rychle", (15, -1.6), p=1, param_pos="above")
net.place("spal_n", (16.5, 1.6))
net.place("spal_z", (16.5, -1.6))
net.timed("t_n", (18, 1.6), "4 min", param_pos="below")
net.timed("t_z", (18, -1.6), "2 min", param_pos="above")
net.arc("na_lince", "normal", via=[(12, 1.6)])
net.arc("na_lince", "rychle", via=[(12, -1.6)])
net.chain("normal", "spal_n", "t_n")
net.chain("rychle", "spal_z", "t_z")
net.place("hotovo", (19.5, 0))
net.immediate("uvolneni", (21, 0), label="uvolnění linky", label_pos="above")
net.arc("t_n", "hotovo", via=[(19.5, 1.6)])
net.arc("t_z", "hotovo", via=[(19.5, -1.6)])
net.arc("hotovo", "uvolneni")
net.place("spaleno", (22.5, 0), label="spáleno", label_pos="below")
net.immediate("odchod", (24, 0), exit=True, label="odchod", label_pos="above")
net.chain("uvolneni", "spaleno", "odchod")
# návrat linky oklikou pod poruchami, do Linky zleva
net.arc("uvolneni", "linka", via=[(21, -7.6), (4.8, -7.6), (4.8, -3.2)])

# poruchy: počkají na dokončení kubíku a mají přednost před dalším zahájením (p=1)
net.place("gen_p", (6, -4.8), tokens=1, label="příchody poruch", label_pos="below")
net.timed("vznik_p", (7.5, -4.8), "exp(3 d)", param_pos="above")
net.loop("gen_p", "vznik_p")
net.place("porucha", (9, -4.8), label="porucha", label_pos="above")
net.arc("vznik_p", "porucha")
net.immediate("oprava", (10.5, -4.8), p=1, param_pos="below")
net.arc("porucha", "oprava")
net.arc("linka", "oprava")
net.place("opravuje", (12, -4.8), label="oprava", label_pos="below")
net.timed("t_oprava", (13.5, -4.8), "5 h", param_pos="below right")
net.chain("oprava", "opravuje", "t_oprava")
net.arc("t_oprava", "linka", out=90, into=0)    # návrat linky po opravě: oblouk z horní strany

# po opravě 5 h zrychlený režim (stav testuje rychlá větev, odpočet je zvlášť)
net.place("rezim_z", (15, -3.2), label="zrychlený režim", label_pos="below right")
net.loop("rezim_z", "rychle")
net.arc("t_oprava", "rezim_z", via=[(15, -4.8)])
net.place("zrychl", (13.5, -6.4))
net.timed("t_zrychl", (15.75, -6.4), "5 h", param_pos="below")
net.place("konec_z", (18, -6.4))
net.immediate("zpomal", (18, -4.8), label="konec zrychlení", label_pos="right")
net.chain("t_oprava", "zrychl", "t_zrychl", "konec_z", "zpomal")
net.arc("rezim_z", "zpomal", via=[(18, -3.2)])

net.invariant({"linka": 1, "na_lince": 1, "spal_n": 1, "spal_z": 1, "hotovo": 1, "opravuje": 1}, 1)
net.invariant({"sklad": 1, "volne": 1, "vyklada": 1}, 100, name="sklad + volné + vykládané = 100")
# sklad přeteče jen výjimečně (porucha během opravy = 10 h bez spalování), proto delší běh
net.sim_events = 300000
