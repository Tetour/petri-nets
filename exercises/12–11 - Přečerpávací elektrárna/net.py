from pn import Net

net = Net("12–11", "Přečerpávací elektrárna (půlsemestrálky 2014–19, Z3)")

# nádrže a přesuny vody; režim (denní / noční / havarijní) je značka, přesun ji testuje
net.place("A", (0, 0), tokens=500, label="A", label_pos="left")
net.place("B", (9, 0), tokens=500, label="B", label_pos="right")
net.place("den_p", (4.5, 4.4), tokens=1, label="denní provoz", label_pos="above left")
net.timed("t_den", (4.5, 2.8), "4 min", param_pos="below")
net.loop("den_p", "t_den", bend=30)
net.arc("A", "t_den", via=[(0, 2.8)])
net.arc("t_den", "B", via=[(9, 2.8)])
net.place("noc_p", (4.5, 1.4), label="noční provoz", label_pos="below right")
net.timed("t_noc", (4.5, 0), "1 min", param_pos="below")
net.loop("noc_p", "t_noc", bend=30)
net.arc("B", "t_noc")
net.arc("t_noc", "A")
net.place("hav_p", (4.5, -4.4), label="havarijní provoz", label_pos="left")
net.timed("t_hav", (4.5, -2.8), "1 min", param_pos="above")
net.loop("hav_p", "t_hav", bend=30)
net.arc("A", "t_hav", via=[(0, -2.8)])
net.arc("t_hav", "B", via=[(9, -2.8)])

# hodiny: den 16 h, noc 8 h; konec dne / noci je signál pro přepnutí režimu
net.place("den", (-4.5, 9.0), tokens=1, label="den", label_pos="left")
net.timed("t16", (-3, 9.0), "16 h", param_pos="below")
net.place("noc", (-1.5, 9.0), label="noc", label_pos="right")
net.timed("t8", (-3, 7.6), "8 h", param_pos="below left")
net.arc("den", "t16")
net.arc("t16", "noc")
net.arc("noc", "t8", via=[(-1.5, 7.6)])
net.arc("t8", "den", via=[(-4.5, 7.6)])
net.place("sig_noc", (-3, 10.6), label="konec dne", label_pos="above")
net.arc("t16", "sig_noc")
net.place("sig_den", (-1.5, 6.8), label="konec noci", label_pos="below")
net.arc("t8", "sig_den", via=[(-3, 6.8)])

# přepnutí na noc (vlevo) a na den (vpravo)
net.immediate("na_noc", (-1.8, 1.4), label="na noc", label_pos="below")
net.arc("den_p", "na_noc", via=[(-1.8, 4.4)])
net.arc("sig_noc", "na_noc", via=[(-6, 10.6), (-6, 1.4)])
net.arc("na_noc", "noc_p")
net.immediate("na_den", (10.8, 1.4), label="na den", label_pos="below")
net.arc("noc_p", "na_den")
net.arc("sig_den", "na_den", via=[(12.3, 6.8), (12.3, 1.4)])

# do denního provozu se vrací přes místo „návrat ke dni“ (z noci i po havárii)
net.place("ke_dni", (7.5, 4.4), label="návrat ke dni", label_pos="above")
net.immediate("do_dne", (6, 4.4))
net.chain("ke_dni", "do_dne", "den_p")
net.arc("na_den", "ke_dni", via=[(10.8, 3.6), (7.5, 3.6)])

# havárie: jen v běžném denním provozu zvýší výrobu na 3 h, jinak bez účinku
net.place("gen_h", (16, 10.6), tokens=1, label="příchody havárií", label_pos="left")
net.timed("vznik", (16, 9.0), "exp(100 d)", param_pos="left")
net.loop("gen_h", "vznik")
net.place("havarie", (16, 7.4), label="havárie", label_pos="left")
net.arc("vznik", "havarie")
net.immediate("bez_ucinku", (17.5, 7.4), label="bez účinku", label_pos="right")
net.arc("havarie", "bez_ucinku")
net.immediate("zvyseni", (16, 4.4), p=1, label="zvýšení výroby", label_pos="below right",
              param_pos="above right")
net.arc("havarie", "zvyseni")
net.arc("den_p", "zvyseni", via=[(4.5, 5.8), (15, 5.8), (15, 4.4)])
net.arc("zvyseni", "hav_p", via=[(19, 4.4), (19, -5.8), (4.5, -5.8)])
net.place("trvani", (16, 2.8))
net.timed("t3", (16, 1.4), "3 h", param_pos="right")
net.place("konec_h", (16, 0))
net.chain("zvyseni", "trvani", "t3", "konec_h")
net.immediate("navrat", (14.5, 0), label="návrat", label_pos="below left")
net.arc("konec_h", "navrat")
net.arc("hav_p", "navrat", via=[(14.5, -4.4)])
net.arc("navrat", "ke_dni", via=[(14.5, 4.4)])

net.closed = True  # voda jen obíhá mezi nádržemi, žádná transakce systém neopouští
net.invariant({"A": 1, "B": 1}, 1000)
net.bound("A", 1000)  # kapacita nádrží se nikdy nepřekročí
net.bound("B", 1000)
net.invariant({"den": 1, "noc": 1}, 1)
net.invariant({"den_p": 1, "noc_p": 1, "hav_p": 1, "ke_dni": 1}, 1, name="právě jeden režim")
net.invariant({"hav_p": 1, "trvani": -1}, 0, name="havarijní provoz = běží 3 h")
net.bound("ke_dni", 0)
net.bound("sig_noc", 1)
net.bound("sig_den", 1)
net.bound("havarie", 0)
# havárie exp(100 d), přesuny po 1–4 min: ~500 událostí za den, ~600 dní simulace
net.sim_events = 300000
