from pn import Net

net = Net("Banka se třemi pracovníky (půlsemestrálka 2013/14, varianta A)")

# příchody a stroj na lístky (jedno zařízení)
net.place("gen", (0, 0), tokens=1, label="příchody klientů", label_pos="below")
net.timed("prichod", (1.5, 0), "exp(5 min)", param_pos="above")
net.loop("gen", "prichod")
net.place("fronta", (3, 0), label="fronta na lístek", label_pos="below")
net.place("automat", (4.5, 1.6), tokens=1, label="Stroj na lístky", label_pos="above")
net.immediate("obsaz_aut", (4.5, 0))
net.place("listek", (6, 0))
net.timed("vydej", (7.5, 0), "30–60 s", param_pos="below")
net.chain("prichod", "fronta", "obsaz_aut", "listek", "vydej")
net.arc("automat", "obsaz_aut")
net.arc("vydej", "automat", out=90, into=0)

# rozdělení: 90 % nahoru na přepážky, 10 % dolů k vedoucímu
net.place("rozdeleni", (9, 0), label="rozdělování", label_pos="right")
net.arc("vydej", "rozdeleni")
net.immediate("na_prep", (10.5, 2.4), prob=90, param_pos="above")
net.immediate("na_ved", (10.5, -2.4), prob=10, param_pos="below")
net.arc("rozdeleni", "na_prep", via=[(9, 2.4)])
net.arc("rozdeleni", "na_ved", via=[(9, -2.4)])

# tři pracovníci na přepážkách (sklad se 3 značkami)
net.place("fronta_p", (12, 2.4), label="fronta", label_pos="below")
net.place("prepazky", (13.5, 4), tokens=3, label="Přepážky (3 pracovníci)", label_pos="above")
net.immediate("obsaz_p", (13.5, 2.4))
net.place("obsluha_p", (15, 2.4))
net.timed("obsl_p", (16.5, 2.4), "exp(5 min)", param_pos="below")
net.chain("na_prep", "fronta_p", "obsaz_p", "obsluha_p", "obsl_p")
net.arc("prepazky", "obsaz_p")
net.arc("obsl_p", "prepazky", out=90, into=0)

# vedoucí: speciální poradenství
net.place("fronta_v", (12, -2.4), label="fronta", label_pos="above")
net.immediate("obsaz_v", (13.5, -2.4))
net.place("poradenstvi", (15, -2.4))
net.timed("obsl_v", (16.5, -2.4), "exp(5 min)", param_pos="above")
net.chain("na_ved", "fronta_v", "obsaz_v", "poradenstvi", "obsl_v")

# odchod klientů
net.place("konec", (18, 0), label="konec", label_pos="left")
net.immediate("odchod", (19.5, 0), exit=True, label="odchod", label_pos="above")
net.arc("obsl_p", "konec", via=[(18, 2.4)])
net.arc("obsl_v", "konec", via=[(18, -2.4)])
net.arc("konec", "odchod")

# vedoucí jako proces: u přepážky (Vedoucí) obsluhuje klienta, po 30 min bez klienta jde na
# kontrolu, nebo obsluhuje auto; ze všech tří činností se vrací přes „vrací se“
net.place("vedouci", (13.5, -4.4), tokens=1, label="Vedoucí", label_pos="above left")
net.arc("vedouci", "obsaz_v")
net.place("navrat", (16.5, -4.4), label="vrací se", label_pos="above right")
net.immediate("navrat_t", (15, -4.4))
net.arc("obsl_v", "navrat")
net.chain("navrat", "navrat_t", "vedouci")
net.timed("necinnost", (11.7, -4.4), "30 min", param_pos="below")
net.place("kontrola", (9.6, -4.4), label="kontrola pobočky", label_pos="above")
net.timed("kontrola_t", (7.8, -4.4), "10–20 min", param_pos="left")
net.chain("vedouci", "necinnost", "kontrola", "kontrola_t")
net.arc("kontrola_t", "navrat", via=[(7.8, -12.2), (19.5, -12.2), (19.5, -4.4)])

# auto s hotovostí (p=1: vedoucí ho obslouží dřív než dalšího klienta)
net.place("gen_a", (13.5, -10.6), tokens=1, label="příjezdy aut", label_pos="left")
net.timed("prijezd", (13.5, -9.2), "exp(5 h)", param_pos="right")
net.loop("gen_a", "prijezd")
net.place("auto", (13.5, -7.8), label="auto čeká", label_pos="left")
net.arc("prijezd", "auto")
net.immediate("obsaz_a", (13.5, -6.2), p=1, param_pos="left")
net.arc("vedouci", "obsaz_a")
net.arc("auto", "obsaz_a")
net.immediate("preruseni", (15, -7.8), p=1, label="přerušení kontroly", label_pos="below right",
              param_pos="above right")
net.arc("auto", "preruseni")
net.arc("kontrola", "preruseni", via=[(9.6, -11.6), (15, -11.6)])
net.place("obsluha_a", (15, -6.2), label="obsluha auta", label_pos="above")
net.arc("obsaz_a", "obsluha_a")
net.arc("preruseni", "obsluha_a")
net.timed("obsl_a", (16.5, -6.2), "10–15 min", param_pos="below")
net.arc("obsluha_a", "obsl_a")
net.arc("obsl_a", "navrat")
net.place("odjezd", (18, -6.2), label="obslouženo", label_pos="above")
net.immediate("odjezd_t", (18, -7.6), exit=True, label="odjezd auta", label_pos="left")
net.chain("obsl_a", "odjezd", "odjezd_t")

net.invariant({"automat": 1, "listek": 1}, 1)
net.invariant({"prepazky": 1, "obsluha_p": 1}, 3)
net.invariant({"vedouci": 1, "poradenstvi": 1, "kontrola": 1, "obsluha_a": 1, "navrat": 1}, 1)
net.bound("auto", 3)
