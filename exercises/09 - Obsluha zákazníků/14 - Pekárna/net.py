from pn import Net

net = Net("Pekárna (půlsemestrálky 2014–19, Z14)")

# příchody a obsluha u pultu
net.place("gen", (0, 0), tokens=1, label="příchody zákazníků", label_pos="above")
net.timed("prichod", (1.5, 0), "exp(20 min)", param_pos="below")
net.loop("gen", "prichod")
net.place("fronta", (3, 0), label="fronta", label_pos="above")
net.place("pekar", (5, 1.6), tokens=1, label="Pekař u pultu", label_pos="left")
net.immediate("obsaz", (5, 0))
net.place("zacatek", (7, 0), label="začátek obsluhy", label_pos="above")
net.immediate("prodej", (8.5, 0), p=1, param_pos="above")
net.place("obsluha", (10, 0))
net.timed("obsl", (11.5, 0), "1–2 min", param_pos="below")
net.chain("prichod", "fronta", "obsaz", "zacatek", "prodej", "obsluha", "obsl")
net.arc("pekar", "obsaz")
net.arc("obsl", "pekar", out=90, into=0)
net.place("chleba", (8.5, -1.6), tokens=20, label="Chléb na pultě", label_pos="below")
net.arc("chleba", "prodej")
net.place("konec", (13, 0), label="s chlebem", label_pos="above")
net.immediate("odchod", (14.5, 0), exit=True, label="odchod", label_pos="above")
net.chain("obsl", "konec", "odchod")

# na začátku obsluhy došel chléb (p=0): zákazník odchází, pekař jde péct
net.immediate("doslo", (7, -3.6), label="došel chléb", label_pos="above right")
net.arc("zacatek", "doslo")
net.place("pece", (9, -3.6))
net.timed("peceni", (10.5, -3.6), "2 h", param_pos="below")
net.place("upeceno", (12, -3.6), label="upečeno", label_pos="below")
net.immediate("navrat", (13.5, -3.6), label="návrat k pultu", label_pos="above")
net.chain("doslo", "pece", "peceni", "upeceno", "navrat")
net.arc("peceni", "chleba", w=20, via=[(10.5, -1.6)], w_pos="right")
net.arc("navrat", "pekar", via=[(15.5, -3.6), (15.5, 2.8), (5, 2.8)])

# během pečení odcházejí čekající i nově příchozí (smyčka na stavu „Pekař peče“)
net.place("peceS", (7, -5.2), label="Pekař peče", label_pos="below")
net.arc("doslo", "peceS")
net.arc("peceS", "navrat", via=[(13.5, -5.2)])
net.immediate("vyprazdni", (5, -5.2), label="vyprázdnění fronty", label_pos="below left")
net.arc("fronta", "vyprazdni", via=[(3, -5.2)])
net.loop("peceS", "vyprazdni", bend=20)
net.place("pryc", (5, -3.6), label="bez chleba", label_pos="above left")
net.arc("doslo", "pryc")
net.arc("vyprazdni", "pryc")
net.immediate("odchod_b", (5, -1.8), exit=True, label="odchod", label_pos="right")
net.arc("pryc", "odchod_b")

net.invariant({"pekar": 1, "zacatek": 1, "obsluha": 1, "pece": 1, "upeceno": 1}, 1)
net.invariant({"peceS": 1, "pece": -1, "upeceno": -1}, 0, name="Pekař peče = pece + upečeno")
net.bound("chleba", 20)
