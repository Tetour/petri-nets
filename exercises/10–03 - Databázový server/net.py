from pn import Net

net = Net("10–03", "Databázový server (půlsemestrálky 2014–19, Z22)", unit="s")

# příchody požadavků
net.place("gen", (0, 0), tokens=1, label="generátor", label_pos="above")
net.timed("prichod", (1.5, 0), "exp(1 s)")
net.loop("gen", "prichod")
net.place("fronta", (3, 0), label="Fronta", label_pos="above right")
net.arc("prichod", "fronta")

# proces A
net.place("a", (4.5, 3.6), tokens=1, label="Proces A", label_pos="left")
net.immediate("obsaz_a", (4.5, 2))
net.place("obsluha_a", (6, 2))
net.timed("vyrizeni_a", (7.5, 2), "exp(0,5 s)")
net.arc("fronta", "obsaz_a")
net.chain("obsaz_a", "obsluha_a", "vyrizeni_a")
net.arc("a", "obsaz_a")
net.arc("vyrizeni_a", "a", bend=-25)

# proces B (obsluhuje, jen když je aktivní)
net.place("b", (4.5, -3.6), label="Proces B aktivní", label_pos="left")
net.immediate("obsaz_b", (4.5, -2))
net.place("obsluha_b", (6, -2))
net.timed("vyrizeni_b", (7.5, -2), "exp(0,5 s)", param_pos="above")
net.arc("fronta", "obsaz_b")
net.chain("obsaz_b", "obsluha_b", "vyrizeni_b")
net.arc("b", "obsaz_b")
net.arc("vyrizeni_b", "b", bend=25)

net.place("konec", (9, 0), label="vyřízeno", label_pos="above right")
net.immediate("odchod", (10.5, 0), exit=True, label="odchod", label_pos="right")
net.arc("vyrizeni_a", "konec")
net.arc("vyrizeni_b", "konec")
net.arc("konec", "odchod")

# proces S: minutu počítá dokončené obsluhy procesu A, pak vyhodnotí a čítač vynuluje
net.place("citac", (9, 3.6), label="obslouženo A", label_pos="above")
net.arc("vyrizeni_a", "citac")
net.place("s_pocita", (16.5, 5.2), tokens=1, label="S počítá", label_pos="right")
net.timed("minuta", (15, 6.8), "1 min", param_pos="below")
net.place("s_vyhodnoti", (13.5, 6.8), label="S vyhodnocuje", label_pos="above")
net.chain("s_pocita", "minuta", "s_vyhodnoti")
net.immediate("naplanuj", (12, 5.2), p=1, horizontal=True, label="naplánuj B",
              label_pos="above left", param_pos="below left")
net.immediate("nenaplanuj", (13.5, 5.2), horizontal=True, label="jinak", label_pos="right")
net.arc("s_vyhodnoti", "naplanuj")
net.arc("s_vyhodnoti", "nenaplanuj")
net.arc("citac", "naplanuj", w=70, w_pos="left")
net.place("s_nuluje", (13.5, 3.6), label="S nuluje", label_pos="below")
net.arc("naplanuj", "s_nuluje")
net.arc("nenaplanuj", "s_nuluje")
net.immediate("nulovani", (11.25, 3.6), p=1, param_pos="below")
net.arc("citac", "nulovani")
net.arc("s_nuluje", "nulovani", bend=-20)
net.arc("nulovani", "s_nuluje", bend=-20)
net.immediate("novy_cyklus", (15, 3.6))
net.arc("s_nuluje", "novy_cyklus")
net.arc("novy_cyklus", "s_pocita")

# aktivace procesu B na 1 min (plán počká, když B právě běží)
net.place("plan", (13.5, -2), label="B naplánován", label_pos="above")
net.arc("naplanuj", "plan", via=[(12, 8.4), (18, 8.4), (18, -2)])
net.place("b_spi", (12, -5.2), tokens=1, label="B čeká", label_pos="below")
net.immediate("aktivace", (12, -3.6), horizontal=True, label="aktivace B", label_pos="above left")
net.arc("plan", "aktivace")
net.arc("b_spi", "aktivace")
net.arc("aktivace", "b")
net.place("b_bezi", (13.5, -5.2))
net.arc("aktivace", "b_bezi")
net.timed("b_minuta", (13.5, -6.8), "1 min", horizontal=True)
net.place("b_konci", (6, -6.8), label="minuta uplynula", label_pos="below")
net.arc("b_bezi", "b_minuta")
net.arc("b_minuta", "b_konci")
net.immediate("deaktivace", (4.5, -5.2), p=1, horizontal=True, label="deaktivace B",
              label_pos="left", param_pos="below left")
net.arc("b_konci", "deaktivace")
net.arc("b", "deaktivace")
net.arc("deaktivace", "b_spi")

net.invariant({"a": 1, "obsluha_a": 1}, 1)
net.invariant({"b_spi": 1, "b": 1, "obsluha_b": 1}, 1)
net.invariant({"s_pocita": 1, "s_vyhodnoti": 1, "s_nuluje": 1}, 1)
net.sim_events = 200000
