from pn import Net

net = Net("03–05", "M/M/1, kritická havárie odstaví linku na 10, rozpracovaná obsluha končí bez náhrady")
net.params = {"A": 10, "B": 6}

# M/M/1 (rozmístění jako v 03–02)
net.place("gen", (0, 0), tokens=1, label="generátor", label_pos="above")
net.timed("prichod", (1.5, 0), "exp(A)")
net.loop("gen", "prichod")
net.place("fronta", (3, 0), label="Fronta")
net.place("linka", (5.4, 1.7), tokens=1, label="Linka", label_pos="left")
net.immediate("obsaz", (4.5, 0))
net.place("obsluha", (6.3, 0))
net.timed("obsl", (7.8, 0), "exp(B)")
net.chain("prichod", "fronta", "obsaz", "obsluha", "obsl")
net.arc("linka", "obsaz")
net.arc("obsl", "linka", bend=-25)
net.place("konec", (9.3, 0))
net.immediate("odchod", (10.8, 0), exit=True, label="odchod")
net.chain("obsl", "konec", "odchod")

# poruchy
net.place("gen_p", (10.8, -1.8), tokens=1, label="generátor havárií", label_pos="above")
net.timed("vznik", (9.3, -1.8), "exp(100)", param_pos="below")
net.loop("gen_p", "vznik")
net.place("porucha", (7.8, -1.8), label="havárie", label_pos="below")
net.arc("vznik", "porucha")
# obsazená linka: havárie ukončí obsluhu a uvolní linku (havárie trvá dál)
net.immediate("preruseni", (5.4, -1.8), p=1, horizontal=True, param_pos="below")
net.arc("obsluha", "preruseni")
net.arc("porucha", "preruseni", bend=-15)
net.arc("preruseni", "porucha", bend=-15)
net.arc("preruseni", "linka")
net.place("zrusena", (3.6, -1.8), label="zrušená", label_pos="above")
net.arc("preruseni", "zrusena")
net.immediate("odchod_z", (2.1, -1.8), exit=True, label="odchod bez obsluhy", label_pos="below")
net.arc("zrusena", "odchod_z")
# volná linka: havárie ji zabere (p=1, má přednost před obsazením transakcí)
net.immediate("zabrani", (8.55, 3.2), p=1, horizontal=True, param_pos="above")
net.arc("porucha", "zabrani", via=[(8.55, -0.9)])
net.arc("linka", "zabrani")
net.place("oprava", (7.0, 3.2), label="odstávka", label_pos="above")
net.arc("zabrani", "oprava")
net.timed("opr", (5.4, 3.2), "10", horizontal=True, param_pos="above")
net.arc("oprava", "opr")
net.arc("opr", "linka")

net.invariant({"linka": 1, "obsluha": 1, "oprava": 1}, 1)
