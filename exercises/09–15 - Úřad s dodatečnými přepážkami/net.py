from pn import Net

net = Net("09–15", "Úřad s dodatečnými přepážkami (půlsemestrálky 2014–19, Z10)")

# klienti a 3 (dočasně 6) přepážky
net.place("gen", (0, 0), tokens=1, label="generátor", label_pos="above left")
net.timed("prichod", (1.5, 0), "exp(10 min)", param_pos="above")
net.loop("gen", "prichod")
net.place("fronta", (3, 0), label="Fronta", label_pos="below left")
net.place("prepazky", (4.5, 1.7), tokens=3, label="Přepážky", label_pos="above right")
net.immediate("obsaz", (4.5, 0))
net.place("obsluha", (6, 0))
net.timed("obsl", (7.5, 0), "exp(15 min)")
net.chain("prichod", "fronta", "obsaz", "obsluha", "obsl")
net.arc("prepazky", "obsaz")
net.arc("obsl", "prepazky", bend=-15)
net.place("konec", (9, 0), label="hotovo", label_pos="above")
net.immediate("odchod", (10.5, 0), exit=True, label="odchod", label_pos="below")
net.chain("obsl", "konec", "odchod")

# fronta >= 10: otevřít 3 dodatečné přepážky na 2 h (stejně jako 09–08)
net.place("nepridano", (1.5, 3.4), tokens=1, label="nepřidáno", label_pos="left")
net.immediate("otevri", (3, 3.4), label="otevři", label_pos="above")
net.arc("nepridano", "otevri")
net.arc("fronta", "otevri", w=10, bend=-15, w_pos="right")
net.arc("otevri", "fronta", w=10, bend=-15, w_pos="left")
net.arc("otevri", "prepazky", w=3, w_pos="above right")
net.place("pridano", (4.5, 3.4), label="přidáno", label_pos="above")
net.timed("dve_h", (6, 3.4), "2 h", param_pos="above")
net.place("zavirani", (7.5, 3.4), label="chci 3 zpět", label_pos="right")
net.chain("otevri", "pridano", "dve_h")
net.arc("dve_h", "zavirani", w=3, w_pos="above")
net.immediate("zavri", (7.5, 1.7), p=1, horizontal=True, param_pos="above left")
net.arc("zavirani", "zavri")
net.arc("prepazky", "zavri")
net.place("zavreno", (10.6, 1.7), label="zavřeno", label_pos="right")
net.arc("zavri", "zavreno")
net.immediate("obnov", (10.6, 3.4), horizontal=True, label="obnov stav", label_pos="right")
net.arc("zavreno", "obnov", w=3, w_pos="right")
net.arc("obnov", "nepridano", via=[(10.6, 7.4), (1.5, 7.4)])

# konec pracovní doby: dodatečné přepážky se zavírají hned (p=1), ne až po 2 h
net.place("konec_top", (7.5, 5.2), label="zavírání", label_pos="above right")
net.immediate("zrus", (6, 5.2), p=1, horizontal=True, param_pos="above")
net.arc("konec_top", "zrus")
net.arc("pridano", "zrus")
net.arc("zrus", "zavirani", w=3, w_pos="left")
net.immediate("nic", (7.5, 6.2), horizontal=True, label="nejsou otevřené", label_pos="above")
net.arc("konec_top", "nic")

# pracovní doba 8 h / volno 16 h
net.place("prac", (6, -3.6), tokens=1, label="pracovní doba", label_pos="below")
net.timed("osm_h", (4.5, -3.6), "8 h", param_pos="below")
net.place("konec_dne", (3, -3.6), label="konec dne", label_pos="below")
net.chain("prac", "osm_h", "konec_dne")
net.arc("osm_h", "konec_top", via=[(4.5, -2.7), (12.8, -2.7), (12.8, 5.2)])
# klienti ve frontě odcházejí (p=1, dokud je fronta neprázdná)
net.immediate("vyhod", (3, -1.8), p=1, horizontal=True, param_pos="left")
net.arc("fronta", "vyhod")
net.loop("konec_dne", "vyhod", bend=20)
net.arc("vyhod", "konec", via=[(9, -1.8)])
# pak (p=0) uzavření úřadu: generátor ztratí značku
net.immediate("zavreni", (1.5, -3.6), horizontal=True, label="zavření úřadu", label_pos="above")
net.arc("konec_dne", "zavreni")
net.arc("gen", "zavreni", via=[(0, -3.6)])
net.place("volno", (1.5, -5.2), label="volno", label_pos="left")
net.timed("sestnact_h", (4.5, -5.2), "16 h", horizontal=True, param_pos="below")
net.chain("zavreni", "volno", "sestnact_h", "prac")
net.arc("sestnact_h", "gen", via=[(5.4, -5.2), (5.4, -6.4), (-0.9, -6.4), (-0.9, 0)])

# 3 základní + 3 dodatečné: nepřidané v „nepřidáno“ (3×), zavřené v „zavřeno“
net.invariant({"prepazky": 1, "obsluha": 1, "nepridano": 3, "zavreno": 1}, 6)
net.invariant({"nepridano": 3, "pridano": 3, "zavirani": 1, "zavreno": 1}, 3)
net.invariant({"prac": 1, "konec_dne": 1, "volno": 1}, 1)
net.invariant({"gen": 1, "volno": 1}, 1)
net.bound("konec_top", 1)
net.sim_events = 300000
