from pn import Net

net = Net("09–15", "Úřad s dodatečnými přepážkami (půlsemestrálky 2014–19, Z10)")

# klienti a 3 (dočasně 6) přepážky
net.place("gen", (0, 0), tokens=1, label="příchody klientů", label_pos="above")
net.timed("prichod", (1.5, 0), "exp(10 min)", param_pos="below")
net.loop("gen", "prichod")
net.place("fronta", (3, 0), label="Fronta", label_pos="below right")
net.place("prepazky", (4.5, 1.6), tokens=3, label="Přepážky", label_pos="above right")
net.immediate("obsaz", (4.5, 0))
net.place("obsluha", (6, 0))
net.timed("obsl", (7.5, 0), "exp(15 min)", param_pos="below")
net.chain("prichod", "fronta", "obsaz", "obsluha", "obsl")
net.arc("prepazky", "obsaz")
net.arc("obsl", "prepazky", out=90, into=0)
net.place("konec", (9, 0), label="hotovo", label_pos="above")
net.immediate("odchod", (10.5, 0), exit=True, label="odchod", label_pos="above")
net.chain("obsl", "konec", "odchod")

# fronta >= 10: otevřít 3 dodatečné přepážky na 2 h (stejně jako 09–08);
# cyklus nepřidáno -> otevři -> přidáno -> 2 h -> chci 3 zpět -> zavři -> zavřeno -> obnov
net.immediate("otevri", (3, 1.6), label="otevři", label_pos="above left")
net.arc("fronta", "otevri", w=10, bend=25, w_pos="left")
net.arc("otevri", "fronta", w=10, bend=25, w_pos="right")
net.arc("otevri", "prepazky", w=3, w_pos="above")
net.place("nepridano", (3, 4.4), tokens=1, label="nepřidáno", label_pos="left")
net.arc("nepridano", "otevri")
net.place("pridano", (9, 4.4), label="přidáno", label_pos="right")
net.arc("otevri", "pridano", via=[(1.5, 1.6), (1.5, 7.6), (9, 7.6)])
net.timed("dve_h", (7.5, 4.4), "2 h", param_pos="above")
net.place("zavirani", (6, 4.4), label="chci 3 zpět", label_pos="above")
net.arc("pridano", "dve_h")
net.arc("dve_h", "zavirani", w=3, w_pos="above")
net.immediate("zavri", (4.5, 4.4), p=1, param_pos="below left")
net.arc("zavirani", "zavri")
net.arc("prepazky", "zavri")
net.place("zavreno", (4.5, 6), label="zavřeno", label_pos="right")
net.arc("zavri", "zavreno")
net.immediate("obnov", (3, 6), label="obnov stav", label_pos="above")
net.arc("zavreno", "obnov", w=3, w_pos="above")
net.arc("obnov", "nepridano")

# konec pracovní doby: dodatečné přepážky se zavírají hned (p=1), ne až po 2 h
net.place("konec_top", (10.5, 2.8), label="zavírání", label_pos="below left")
net.immediate("zrus", (7.5, 2.8), p=1, param_pos="above")
net.arc("pridano", "zrus", via=[(9, 2.8)])
net.arc("konec_top", "zrus", via=[(10.5, 2), (7.5, 2)])
net.arc("zrus", "zavirani", w=3, via=[(6, 2.8)], w_pos="below")
net.immediate("nic", (12, 2.8), label="nejsou otevřené", label_pos="below")
net.arc("konec_top", "nic")

# pracovní doba 8 h / volno 16 h
net.place("prac", (4.5, -4.8), tokens=1, label="pracovní doba", label_pos="below")
net.timed("osm_h", (4.5, -3.2), "8 h", param_pos="above right")
net.place("konec_dne", (3, -3.2), label="konec dne", label_pos="below")
net.arc("prac", "osm_h")
net.arc("osm_h", "konec_dne")
net.arc("osm_h", "konec_top", via=[(13.2, -3.2), (13.2, 3.8), (10.5, 3.8)])
# klienti ve frontě odcházejí (p=1, dokud je fronta neprázdná)
net.immediate("vyhod", (3, -1.6), p=1, param_pos="left")
net.arc("fronta", "vyhod")
net.loop("konec_dne", "vyhod", bend=20)
net.arc("vyhod", "konec", via=[(9, -1.6)])
# pak (p=0) uzavření úřadu: generátor ztratí značku
net.immediate("zavreni", (1.5, -3.2), label="zavření úřadu", label_pos="above left")
net.arc("konec_dne", "zavreni")
net.arc("gen", "zavreni", via=[(0, -3.2)])
net.place("volno", (1.5, -4.8), label="volno", label_pos="left")
net.timed("sestnact_h", (3, -4.8), "16 h", param_pos="below right")
net.chain("zavreni", "volno", "sestnact_h", "prac")
net.arc("sestnact_h", "gen", via=[(3, -6), (-0.9, -6), (-0.9, 0)])

# 3 základní + 3 dodatečné: nepřidané v „nepřidáno“ (3×), zavřené v „zavřeno“
net.invariant({"prepazky": 1, "obsluha": 1, "nepridano": 3, "zavreno": 1}, 6)
net.invariant({"nepridano": 3, "pridano": 3, "zavirani": 1, "zavreno": 1}, 3)
net.invariant({"prac": 1, "konec_dne": 1, "volno": 1}, 1)
net.invariant({"gen": 1, "volno": 1}, 1)
net.bound("konec_top", 1)
net.sim_events = 300000
