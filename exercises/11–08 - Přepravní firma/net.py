from pn import Net

net = Net("11–08", "Přepravní firma (půlsemestrálky 2014–19, Z12)")

# A-balíky čekají v centrále; řidič vyráží až s plným autem (20 kusů, nakládání v nulovém čase)
net.place("gen", (-1.5, 0), tokens=1, label="generátor", label_pos="below")
net.timed("prichod", (0, 0), "exp(20 min)", param_pos="below")
net.loop("gen", "prichod")
net.place("a_baliky", (3, 0), label="A-balíky", label_pos="below")
net.place("ridic", (4.5, 1.8), tokens=1, label="Řidič", label_pos="above right")
net.immediate("nalozeni", (4.5, 0), label="naložení", label_pos="above left")
net.chain("prichod", "a_baliky")
net.arc("a_baliky", "nalozeni", w=20, w_pos="below")
net.arc("ridic", "nalozeni")
net.place("v_aute", (6, -1.8), label="balíky v autě", label_pos="below")
net.arc("nalozeni", "v_aute", w=20, w_pos="below left")

# rozvoz: dokud jsou balíky v autě (p=1), jede k dalšímu adresátovi
net.place("trasa", (6, 0), label="na trase", label_pos="below")
net.arc("nalozeni", "trasa")
net.immediate("k_adresatovi", (7.5, 0), p=1, param_pos="above")
net.arc("trasa", "k_adresatovi")
net.arc("v_aute", "k_adresatovi")
net.place("cesta", (9, 0))
net.timed("jizda", (10.5, 0), "exp(10 min)", param_pos="below")
net.place("u_adresata", (12, 0), label="u adresáta", label_pos="above")
net.timed("zastavka", (13.5, 0), "3–5 min", param_pos="below")
net.chain("k_adresatovi", "cesta", "jizda", "u_adresata", "zastavka")
net.arc("zastavka", "trasa", via=[(13.5, 1.3), (7, 1.3)])
net.place("predani", (15, 0), label="předání", label_pos="below")
net.arc("zastavka", "predani")
net.immediate("dorucen", (16.5, -1), prob=80, param_pos="below")
net.immediate("nezastizen", (16.5, 1), prob=20, param_pos="above left")
net.arc("predani", "dorucen")
net.arc("predani", "nezastizen")
net.place("doruceno", (18, -1), label="doručeno", label_pos="below")
net.immediate("odchod", (19.5, -1), exit=True, label="odchod", label_pos="below")
net.chain("dorucen", "doruceno", "odchod")

# auto prázdné (p=0): návrat do centrály
net.immediate("navrat", (6, 1.8), horizontal=True, label="auto prázdné", label_pos="right")
net.arc("trasa", "navrat")
net.place("zpet", (6, 3.4), label="cesta zpět", label_pos="above")
net.timed("jizda_zpet", (4.5, 3.4), "exp(10 min)", param_pos="above")
net.chain("navrat", "zpet", "jizda_zpet", "ridic")

# nezastižení: balík jede v autě zpět, v centrále se vyloží (p=1, dokud nějaký je) jako B-balík
net.place("nedoruceno", (3, 3.4), label="nedoručené v autě", label_pos="above left")
net.arc("nezastizen", "nedoruceno", via=[(16.5, 5.2), (3, 5.2)])
net.immediate("vylozeni", (3, 1.8), p=1, param_pos="above left")
net.arc("nedoruceno", "vylozeni")
net.loop("ridic", "vylozeni", bend=20)
net.place("b_baliky", (1.5, 1.8), label="B-balíky", label_pos="left")
net.timed("den", (1.5, 0.9), "24 h", horizontal=True, param_pos="left")
net.chain("vylozeni", "b_baliky", "den", "a_baliky")

net.invariant({"ridic": 1, "trasa": 1, "cesta": 1, "u_adresata": 1, "zpet": 1}, 1,
              name="řidič je právě v jednom stavu")
net.bound("v_aute", 20)
net.bound("nedoruceno", 20)
