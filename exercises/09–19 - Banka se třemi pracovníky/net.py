from pn import Net

net = Net("09–19", "Banka se třemi pracovníky (půlsemestrálka 2013/14, varianta A)")

# příchody a stroj na lístky (jedno zařízení)
net.place("gen", (0, 0), tokens=1, label="generátor", label_pos="below")
net.timed("prichod", (1.5, 0), "exp(5 min)", param_pos="above")
net.loop("gen", "prichod")
net.place("fronta", (3, 0), label="Fronta na lístek", label_pos="below")
net.place("automat", (4.5, 1.6), tokens=1, label="Stroj na lístky")
net.immediate("obsaz_aut", (4.5, 0))
net.place("listek", (6, 0))
net.timed("vydej", (7.5, 0), "30–60 s")
net.chain("prichod", "fronta", "obsaz_aut", "listek", "vydej")
net.arc("automat", "obsaz_aut")
net.arc("vydej", "automat", bend=-25)

# rozdělení: 90 % přepážky, 10 % poradenství u vedoucího
net.place("rozdeleni", (9, 0), label="rozdělování", label_pos="below")
net.arc("vydej", "rozdeleni")
net.immediate("na_prep", (10.5, 2), prob=90, param_pos="above")
net.immediate("na_ved", (10.5, -2), prob=10, param_pos="below")
net.arc("rozdeleni", "na_prep")
net.arc("rozdeleni", "na_ved")

# tři pracovníci na přepážkách (sklad se 3 značkami)
net.place("fronta_p", (12, 2), label="Fronta na přepážky", label_pos="below")
net.place("prepazky", (13.5, 3.6), tokens=3, label="Přepážky (3 pracovníci)")
net.immediate("obsaz_p", (13.5, 2))
net.place("obsluha_p", (15, 2))
net.timed("obsl_p", (16.5, 2), "exp(5 min)", param_pos="right")
net.chain("na_prep", "fronta_p", "obsaz_p", "obsluha_p", "obsl_p")
net.arc("prepazky", "obsaz_p")
net.arc("obsl_p", "prepazky", bend=-25)

# vedoucí: speciální poradenství
net.place("fronta_v", (12, -2), label="Fronta k vedoucímu", label_pos="above")
net.place("vedouci", (13.5, -3.8), tokens=1, label="Vedoucí", label_pos="below right")
net.immediate("obsaz_v", (13.5, -2))
net.place("poradenstvi", (15, -2))
net.timed("obsl_v", (16.5, -2), "exp(5 min)", param_pos="right")
net.chain("na_ved", "fronta_v", "obsaz_v", "poradenstvi", "obsl_v")
net.arc("vedouci", "obsaz_v")
net.arc("obsl_v", "vedouci", bend=25)

# odchod klientů
net.place("konec", (18, 0), label="konec", label_pos="above")
net.immediate("odchod", (19.5, 0), exit=True, label="odchod", label_pos="above")
net.arc("obsl_p", "konec")
net.arc("obsl_v", "konec")
net.arc("konec", "odchod")

# vedoucí 30 min bez klienta -> kontrola pobočky
net.timed("necinnost", (12, -3.8), "30 min", param_pos="above")
net.place("kontrola", (10.5, -3.8), label="Kontrola pobočky", label_pos="above left")
net.timed("kontrola_t", (12, -5.4), "10–20 min", param_pos="left")
net.chain("vedouci", "necinnost", "kontrola", "kontrola_t", "vedouci")

# auto s hotovostí (p=1: vedoucí ho obslouží dřív než dalšího klienta)
net.place("gen_a", (10.5, -7.4), tokens=1, label="generátor aut", label_pos="above")
net.timed("prijezd", (12, -7.4), "exp(5 h)", param_pos="below")
net.loop("gen_a", "prijezd")
net.place("auto", (13.5, -7.4), label="Auto čeká", label_pos="below")
net.arc("prijezd", "auto")
net.immediate("obsaz_a", (13.5, -5.6), p=1, param_pos="left")
net.arc("vedouci", "obsaz_a")
net.arc("auto", "obsaz_a")
net.immediate("preruseni", (15, -7.4), p=1, label="přerušení kontroly", label_pos="below right",
              param_pos="right")
net.arc("auto", "preruseni")
net.arc("kontrola", "preruseni", via=[(9.3, -3.8), (9.3, -8.8), (15, -8.8)])
net.place("obsluha_a", (15, -5.6), label="Obsluha auta", label_pos="above")
net.arc("obsaz_a", "obsluha_a")
net.arc("preruseni", "obsluha_a")
net.timed("obsl_a", (16.5, -5.6), "10–15 min", param_pos="below")
net.arc("obsluha_a", "obsl_a")
net.arc("obsl_a", "vedouci", via=[(16.5, -3.8)])
net.place("odjezd", (18, -5.6), label="obslouženo", label_pos="above")
net.immediate("odjezd_t", (19.5, -5.6), exit=True, label="odjezd auta", label_pos="below")
net.chain("obsl_a", "odjezd", "odjezd_t")

net.invariant({"automat": 1, "listek": 1}, 1)
net.invariant({"prepazky": 1, "obsluha_p": 1}, 3)
net.invariant({"vedouci": 1, "poradenstvi": 1, "kontrola": 1, "obsluha_a": 1}, 1)
net.bound("auto", 3)
