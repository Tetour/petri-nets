from pn import Net

net = Net("12–10", "Zahradník na FIT (půlsemestrálky 2014–19, Z8)")

# začátek dne: zahradník u zdroje s plnou konví jde k první květině
net.place("start", (0, 0), tokens=1, label="u zdroje (ráno)", label_pos="above")
net.place("kvetiny", (1.5, 1.6), tokens=30, label="Květiny", label_pos="left")
net.timed("k_prvni", (1.5, 0), "2–5 min", param_pos="below")
net.place("u_kv", (3, 0), label="u květiny", label_pos="above right")
net.chain("start", "k_prvni", "u_kv")
net.arc("kvetiny", "k_prvni")

# květina potřebuje 3 (20 %, nahoru) nebo 4 (80 %, rovně); potřeba zůstává u květiny
net.immediate("s3", (4.5, 2.0), prob=20, param_pos="above left")
net.immediate("s4", (4.8, 0), prob=80, param_pos="below right")
net.arc("u_kv", "s3", via=[(3, 2.0)], corner=20)
net.arc("u_kv", "s4")
net.place("n3", (4.5, 3.6), label="potřebuje 3", label_pos="above")
net.place("n4", (4.8, -1.8), label="potřebuje 4", label_pos="left")
net.arc("s3", "n3")
net.arc("s4", "n4")

# zahradník u květiny (z obou větví i po návratu od zdroje)
net.place("w", (6, 0))
net.arc("s3", "w", via=[(6, 2.0)])
net.arc("s4", "w")
net.immediate("t_w", (7.5, 0))
net.place("z", (9, 0), label="zahradník", label_pos="above right")
net.chain("w", "t_w", "z")

# zalití, je-li v konvi dost vody (p=1)
net.immediate("zal3", (10.5, 3.6), p=1, param_pos="above left")
net.immediate("zal4", (10.5, -3.4), p=1, param_pos="below left")
net.arc("n3", "zal3")
net.arc("n4", "zal4", via=[(4.8, -3.4)])
net.arc("z", "zal3", via=[(9, 2.4), (10.5, 2.4)])
net.arc("z", "zal4", via=[(9, -2.4), (10.5, -2.4)])
net.place("zaleva", (12, 3.6), label="zalévá", label_pos="above")
net.arc("zal3", "zaleva")
net.arc("zal4", "zaleva", via=[(12, -3.4)])

# jinak (p=0) cesta ke zdroji, vylití zbytku, napuštění 10 jednotek za 60 s a návrat
net.immediate("dojdi", (11.2, 0), label="málo vody", label_pos="below left")
net.place("ke_zdroji", (13.5, 0))
net.timed("tam", (15, 0), "2–5 min", param_pos="below")
net.place("u_zdroje", (16.5, 0), label="u zdroje", label_pos="below")
net.chain("z", "dojdi", "ke_zdroji", "tam", "u_zdroje")
net.immediate("vylij", (16.5, 1.4), p=1, param_pos="left")
net.loop("u_zdroje", "vylij", bend=30)
net.place("konev", (18, 1.4), tokens=10, label="Konev", label_pos="above left")
net.arc("konev", "vylij")
net.timed("napust", (18, 0), "60 s", param_pos="right")
net.arc("u_zdroje", "napust")
net.arc("napust", "konev", w=10, w_pos="right")
net.arc("konev", "zal3", w=3, w_pos="above", via=[(18, 6.2), (10.5, 6.2)])
net.arc("konev", "zal4", w=4, w_pos="above", via=[(19.4, 1.4), (19.4, -4.6), (10.5, -4.6)])
net.place("zpet", (16.5, -1.2))
net.arc("napust", "zpet", via=[(18, -1.2)])
net.timed("zpet_t", (15, -1.2), "2–5 min", param_pos="below")
net.chain("zpet", "zpet_t")
net.arc("zpet_t", "w", via=[(6, -1.2)])

# po zalití (20 s): květina hotová, zahradník jde k další (p=1), nebo den končí
net.timed("zaliti", (13.5, 3.6), "20 s", param_pos="below")
net.arc("zaleva", "zaliti")
net.place("zalita", (13.5, 5.0), label="zalitá květina", label_pos="left")
net.immediate("odchod", (15, 5.0), exit=True, label="odchod", label_pos="right")
net.arc("zaliti", "zalita")
net.arc("zalita", "odchod")
net.place("po", (15, 3.6), label="po zalití", label_pos="above")
net.arc("zaliti", "po")
net.immediate("k_dalsi", (16.5, 3.6), p=1, param_pos="below")
net.arc("po", "k_dalsi")
net.arc("kvetiny", "k_dalsi", via=[(1.5, 6.6), (16.5, 6.6)])
net.place("cesta", (19.2, 3.6))
net.timed("prejezd", (20.8, 3.6), "exp(1 min)", param_pos="above")
net.chain("k_dalsi", "cesta", "prejezd")
net.arc("prejezd", "u_kv", via=[(20.8, -5.8), (3, -5.8)])
net.immediate("konec", (15, 1.75), label="květiny došly", label_pos="below")
net.place("den", (13.2, 1.75), label="konec dne", label_pos="below")
net.arc("po", "konec")
net.arc("konec", "den")

net.invariant({"start": 1, "u_kv": 1, "w": 1, "z": 1, "ke_zdroji": 1, "u_zdroje": 1, "zpet": 1,
               "zaleva": 1, "po": 1, "cesta": 1, "den": 1}, 1, name="zahradník je právě v jednom stavu")
net.bound("konev", 10)
net.bound("w", 1)
# model jednoho dne: po zalití 30 květin síť skončí (značka v „konec dne“), proto se nehlásí deadlock
net.deadlock_ok = True
