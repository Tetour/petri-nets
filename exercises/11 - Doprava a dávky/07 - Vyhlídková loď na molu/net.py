from pn import Net

net = Net("Vyhlídková loď na molu (půlsemestrálky 2014–19, Z18)")

# příchody; každý čekající po 30 min odchází (vlastní odpočet pro každou značku)
net.place("gen", (0, 0), tokens=1, label="příchody cestujících", label_pos="below")
net.timed("prichod", (1.5, 0), "exp(5 min)", param_pos="above")
net.loop("gen", "prichod")
net.place("fronta", (3, 0), label="fronta", label_pos="below left")
net.arc("prichod", "fronta")
net.timed("netrpelivost", (4.5, 0), "30 min", param_pos="below")
net.arc("fronta", "netrpelivost")
net.place("odesel", (6, 0), label="odešel", label_pos="below")
net.immediate("odchod_f", (7.5, 0), exit=True, label="odchod", label_pos="below")
net.chain("netrpelivost", "odesel", "odchod_f")

# nástup po jednom: loď u mola je prázdná (nahoře), nebo už někdo nastoupil (dole)
net.place("lod0", (4.5, 3.6), tokens=1, label="loď u mola (prázdná)", label_pos="left")
net.place("lod1", (4.5, -3.6), label="loď u mola (s cestujícími)", label_pos="left")
net.immediate("zac0", (4.5, 1.8))
net.immediate("zac1", (4.5, -1.8))
net.arc("fronta", "zac0", via=[(3, 1.8)])
net.arc("fronta", "zac1", via=[(3, -1.8)])
net.arc("lod0", "zac0")
net.arc("lod1", "zac1")
net.place("nastupuje", (9, 0))
net.arc("zac0", "nastupuje", via=[(9, 1.8)])
net.arc("zac1", "nastupuje", via=[(9, -1.8)])
net.timed("nastup", (10.5, 0), "1 min", param_pos="above")
net.place("paluba", (12, 0), label="na palubě", label_pos="above")
net.chain("nastupuje", "nastup", "paluba")

# po nástupu: 20 na palubě → plná loď vyplouvá (p=1), jinak loď čeká na další (p=0)
net.place("po_nastupu", (10.5, -1.8), label="po nástupu", label_pos="below left")
net.arc("nastup", "po_nastupu")
net.immediate("pokracuje", (7.5, -3.6))
net.arc("po_nastupu", "pokracuje", via=[(10.5, -3.6)])
net.arc("pokracuje", "lod1")
net.immediate("plna", (12, -1.8), p=1, label="plná loď", label_pos="below left",
              param_pos="below right")
net.arc("po_nastupu", "plna")
net.loop("paluba", "plna", bend=20, w=20)

# 3 min od posledního nástupu (odpočet běží jen u lodi s cestujícími)
net.timed("cekani", (9, -5.4), "3 min", param_pos="above")
net.arc("lod1", "cekani", via=[(4.5, -5.4)])
net.place("plavba", (13.5, -1.8), label="plavba", label_pos="above right")
net.arc("plna", "plavba")
net.arc("cekani", "plavba", via=[(13.5, -5.4)])
net.timed("t_plavba", (15, -1.8), "1 h", param_pos="below")
net.place("navrat", (16.5, -1.8), label="návrat", label_pos="below")
net.chain("plavba", "t_plavba", "navrat")

# po návratu vystoupí všichni (smyčka p=1), pak je loď opět prázdná u mola
net.immediate("vystup", (16.5, 0), p=1, label="výstup", label_pos="right", param_pos="above right")
net.loop("navrat", "vystup", bend=20)
net.arc("paluba", "vystup")
net.place("konec", (16.5, 1.8), label="konec", label_pos="left")
net.immediate("odchod", (18, 1.8), exit=True, label="odchod", label_pos="below")
net.chain("vystup", "konec", "odchod")
net.immediate("pristavena", (18, -1.8), label="přistavení", label_pos="below")
net.arc("navrat", "pristavena")
net.arc("pristavena", "lod0", via=[(19.5, -1.8), (19.5, 5.4), (4.5, 5.4)])

net.invariant({"lod0": 1, "lod1": 1, "nastupuje": 1, "po_nastupu": 1, "plavba": 1, "navrat": 1}, 1,
              name="loď je právě v jednom stavu")
net.bound("paluba", 20)
