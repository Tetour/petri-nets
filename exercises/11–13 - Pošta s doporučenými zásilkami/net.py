from pn import Net

net = Net("11–13", "Pošta s doporučenými zásilkami (půlsemestrálka 2011/12, příklad 2)")

# každý den 100 nových zásilek (první dávka je na poště od začátku)
net.place("gen_d", (0, 2.0), tokens=1, label="generátor", label_pos="above")
net.timed("t_den", (1.5, 2.0), "1 d", param_pos="above")
net.loop("gen_d", "t_den")
net.place("sklad", (3, 2.0), tokens=100, label="Zásilky na poště", label_pos="above")
net.arc("t_den", "sklad", w=100, w_pos="below")

# tři pracovníci na přepážkách (asistují i u vozu)
net.place("prac", (3, -1.4), tokens=3, label="Pracovníci", label_pos="below left")

# nakládání: vůz nabere 20 zásilek najednou (100 je násobek 20)
net.place("vuz", (1.5, 0), tokens=1, label="Vůz na poště", label_pos="above left")
net.immediate("nabrat", (3, 0), p=1, param_pos="above left")
net.arc("vuz", "nabrat")
net.arc("sklad", "nabrat", w=20, w_pos="left")
net.arc("prac", "nabrat")
net.place("naklada", (4.5, 0))
net.timed("t_nakl", (6, 0), "10–15 min", param_pos="below")
net.chain("nabrat", "naklada", "t_nakl")
net.arc("t_nakl", "prac")
net.place("ve_voze", (9, 1.6), label="Zásilky ve voze", label_pos="above right")
net.arc("nabrat", "ve_voze", w=20, via=[(3.6, 1.6)], w_pos="above")

# vůz bere další zásilku: je-li, jede k zákazníkovi (p=1), jinak se vrací
net.place("rozhod", (7.5, 0), label="další zásilka?", label_pos="above left")
net.arc("t_nakl", "rozhod")
net.immediate("vezmi", (9, 0), p=1, param_pos="below")
net.arc("rozhod", "vezmi")
net.arc("ve_voze", "vezmi")
net.place("jede", (10.5, 0), label="jede", label_pos="below")
net.timed("t_jizda", (12, 0), "exp(2 min)", param_pos="above")
net.place("u_zak", (13.5, 0), label="u zákazníka", label_pos="below")
net.chain("vezmi", "jede", "t_jizda", "u_zak")

# 80 % zastiženo (3–5 min), 20 % nezastiženo (1 min)
net.immediate("zastizen", (15, 1.4), prob=80, param_pos="above")
net.immediate("nezastizen", (15, -1.4), prob=20, param_pos="left")
net.arc("u_zak", "zastizen")
net.arc("u_zak", "nezastizen")
net.place("predava", (16.5, 1.4))
net.timed("t_predani", (18, 1.4), "3–5 min", param_pos="below")
net.chain("zastizen", "predava", "t_predani")
net.place("nezast", (16.5, -1.4))
net.timed("t_nezast", (18, -1.4), "1 min", param_pos="above")
net.chain("nezastizen", "nezast", "t_nezast")
net.arc("t_predani", "rozhod", via=[(18, 2.8), (7.5, 2.8)])
net.arc("t_nezast", "rozhod", via=[(18, -2.2), (8.7, -2.2)])
net.place("doruceno", (19.5, 1.4), label="doručeno", label_pos="above")
net.immediate("odchod_z", (21, 1.4), exit=True, label="odchod", label_pos="above")
net.chain("t_predani", "doruceno", "odchod_z")
net.place("nedoruc", (19.5, -1.4), label="nedoručené ve voze", label_pos="right")
net.arc("t_nezast", "nedoruc")

# po posledním zákazníkovi: cesta zpět exp(2 min)
net.immediate("zpet", (7.5, -1.4), label="poslední", label_pos="right")
net.arc("rozhod", "zpet")
net.place("navrat", (7.5, -2.8))
net.timed("t_navrat", (6, -2.8), "exp(2 min)", param_pos="above")
net.chain("zpet", "navrat", "t_navrat")

# vykládka nedoručených po jedné, exp(2 min), s pracovníkem
net.place("vratil", (4.5, -2.8))
net.arc("t_navrat", "vratil")
net.immediate("vyklad", (3, -2.8), p=1, param_pos="below")
net.arc("vratil", "vyklad")
net.arc("prac", "vyklad")
net.place("vyklada", (1.5, -2.8), label="vykládá", label_pos="below left")
net.arc("vyklad", "vyklada")
net.immediate("hotovo", (0.6, -1.4))
net.arc("vyklada", "hotovo")
net.arc("hotovo", "vuz")
net.arc("hotovo", "prac")
net.immediate("vezmi_n", (0, -2.8), p=1, param_pos="above")
net.arc("vyklada", "vezmi_n")
net.arc("nedoruc", "vezmi_n", via=[(19.5, -6.4), (-1.0, -6.4), (-1.0, -2.8)])
net.place("vyklada_z", (0, -4.2))
net.timed("t_vyklad", (1.5, -4.2), "exp(2 min)", param_pos="right")
net.chain("vezmi_n", "vyklada_z", "t_vyklad", "vyklada")
net.place("uschovna", (1.5, -5.4), label="Úschovna", label_pos="left")
net.arc("t_vyklad", "uschovna")

# zákazníci si chodí pro nedoručené zásilky, 3 přepážky
net.place("gen_z", (4.5, -4.6), tokens=1, label="generátor", label_pos="below")
net.timed("t_zak", (6, -4.6), "exp(10 min)", param_pos="below")
net.loop("gen_z", "t_zak")
net.place("fronta", (7.5, -4.6), label="Fronta", label_pos="below")
net.immediate("obsaz", (9, -4.6))
net.place("obsluha", (10.5, -4.6))
net.timed("t_obsl", (12, -4.6), "1–2 min", param_pos="below")
net.chain("t_zak", "fronta", "obsaz", "obsluha", "t_obsl")
net.arc("prac", "obsaz", via=[(3.8, -1.9), (3.8, -3.8), (9, -3.8)])
net.arc("t_obsl", "prac", via=[(12, -3.5), (4.1, -3.5), (4.1, -1.6)])
net.place("obslouzen", (13.5, -4.6))
net.arc("t_obsl", "obslouzen")
net.immediate("vydej", (15, -4.6), p=1, label="výdej", label_pos="below right",
              param_pos="above")
net.immediate("bez", (15, -3.2), label="bez zásilky", label_pos="above")
net.arc("obslouzen", "vydej")
net.arc("obslouzen", "bez")
net.arc("uschovna", "vydej", via=[(1.5, -5.9), (14.4, -5.9)])
net.place("odchazi", (16.5, -4.6))
net.arc("vydej", "odchazi")
net.arc("bez", "odchazi")
net.immediate("odchod_k", (18, -4.6), exit=True, label="odchod", label_pos="below")
net.arc("odchazi", "odchod_k")

net.invariant({"vuz": 1, "naklada": 1, "rozhod": 1, "jede": 1, "u_zak": 1, "predava": 1,
               "nezast": 1, "navrat": 1, "vratil": 1, "vyklada": 1, "vyklada_z": 1}, 1)
net.invariant({"prac": 1, "naklada": 1, "vyklada": 1, "vyklada_z": 1, "obsluha": 1}, 3)
net.bound("ve_voze", 20)
