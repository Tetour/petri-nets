from pn import Net

net = Net("11–13", "Pošta s doporučenými zásilkami (půlsemestrálka 2011/12, příklad 2)")

# každý den 100 nových zásilek (první dávka je na poště od začátku)
net.place("gen_d", (-1.5, 1.6), tokens=1, label="příchody zásilek", label_pos="above")
net.timed("t_den", (0, 1.6), "1 d", param_pos="above")
net.loop("gen_d", "t_den")
net.place("sklad", (1.5, 1.6), tokens=100, label="Zásilky na poště", label_pos="above")
net.arc("t_den", "sklad", w=100, w_pos="below")

# vůz: nakládání (vůz nabere 20 zásilek najednou, 100 je násobek 20)
net.place("vuz", (0, 0), tokens=1, label="Vůz na poště", label_pos="above left")
net.immediate("nabrat", (1.5, 0), p=1, param_pos="below right")
net.arc("vuz", "nabrat")
net.arc("sklad", "nabrat", w=20, w_pos="right")
net.place("naklada", (3, 0))
net.timed("t_nakl", (5, 0), "10–15 min", param_pos="below left")
net.chain("nabrat", "naklada", "t_nakl")
net.place("ve_voze", (5, 1.6), label="Zásilky ve voze", label_pos="above")
net.arc("t_nakl", "ve_voze", w=20, w_pos="right")

# vůz bere další zásilku: je-li, jede k zákazníkovi (p=1), jinak se vrací (poslední)
net.place("rozhod", (6.5, 0), label="další zásilka?", label_pos="above right")
net.arc("t_nakl", "rozhod")
net.immediate("vezmi", (6.5, 1.6), p=1, param_pos="above")
net.arc("rozhod", "vezmi")
net.arc("ve_voze", "vezmi")
net.place("jede", (8, 1.6), label="jede", label_pos="below")
net.timed("t_jizda", (9.5, 1.6), "exp(2 min)", param_pos="below")
net.place("u_zak", (11, 1.6), label="u zákazníka", label_pos="right")
net.chain("vezmi", "jede", "t_jizda", "u_zak")

# 20 % nezastiženo (nahoru, 1 min), 80 % zastiženo (dolů, 3–5 min)
net.immediate("nezastizen", (12.5, 3.1), prob=20, param_pos="above")
net.immediate("zastizen", (12.5, 0.1), prob=80, param_pos="below")
net.arc("u_zak", "nezastizen", via=[(11, 3.1)], corner=20)
net.arc("u_zak", "zastizen", via=[(11, 0.1)], corner=20)
net.place("nezast", (14, 3.1))
net.timed("t_nezast", (15.5, 3.1), "1 min", param_pos="below")
net.place("nedoruc", (17, 3.1), label="nedoručené ve voze", label_pos="above")
net.chain("nezastizen", "nezast", "t_nezast", "nedoruc")
net.place("predava", (14, 0.1))
net.timed("t_predani", (15.5, 0.1), "3–5 min", param_pos="above")
net.place("doruceno", (17, 0.1), label="doručeno", label_pos="below")
net.immediate("odchod_z", (18.5, 0.1), exit=True, label="odchod", label_pos="below")
net.chain("zastizen", "predava", "t_predani", "doruceno", "odchod_z")
net.arc("t_predani", "rozhod", via=[(15.5, -1.0), (7.5, -1.0), (7.5, 0)])
net.arc("t_nezast", "rozhod", via=[(15.5, 4.6), (22, 4.6), (22, -2.0), (7.9, -2.0)])

# po posledním zákazníkovi: cesta zpět exp(2 min)
net.immediate("zpet", (6.5, -1.6), label="poslední", label_pos="left")
net.arc("rozhod", "zpet")
net.place("navrat", (6.5, -3.2))
net.timed("t_navrat", (6.5, -4.8), "exp(2 min)", param_pos="left")
net.place("vratil", (8, -4.8))
net.chain("zpet", "navrat", "t_navrat", "vratil")

# vykládka nedoručených po jedné, exp(2 min), s pracovníkem
net.immediate("vyklad", (9.5, -4.8), p=1, param_pos="above")
net.place("vyklada", (11.5, -4.8), label="vykládá", label_pos="below left")
net.chain("vratil", "vyklad", "vyklada")
net.immediate("vezmi_n", (11.5, -3.2), p=1, param_pos="left")
net.arc("vyklada", "vezmi_n")
net.arc("nedoruc", "vezmi_n", via=[(20.5, 3.1), (20.5, -2.6), (11.5, -2.6)])
net.place("vyklada_z", (13, -3.2))
net.timed("t_vyklad", (13, -4.8), "exp(2 min)", param_pos="right")
net.chain("vezmi_n", "vyklada_z", "t_vyklad", "vyklada")
net.place("uschovna", (14.5, -7.6), label="Úschovna", label_pos="right")
net.arc("t_vyklad", "uschovna", via=[(13, -7.6)])
net.immediate("hotovo", (11.5, -6.4))
net.arc("vyklada", "hotovo")
net.arc("hotovo", "vuz", via=[(23, -6.4), (23, -13.2), (-1.5, -13.2), (-1.5, 0)])

# tři pracovníci na přepážkách (asistují i u vozu)
net.place("prac", (8, -8.0), tokens=3, label="Pracovníci", label_pos="below left")
net.arc("prac", "nabrat", via=[(1.5, -8.0)])
net.arc("t_nakl", "prac", via=[(5, -6.6), (8, -6.6)])
net.arc("prac", "vyklad", out=45, into=270)
net.arc("hotovo", "prac", via=[(11.5, -8.0)])

# zákazníci si chodí pro nedoručené zásilky, 3 přepážky
net.place("gen_z", (3.5, -10.4), tokens=1, label="příchody zákazníků", label_pos="above")
net.timed("t_zak", (5, -10.4), "exp(10 min)", param_pos="below")
net.loop("gen_z", "t_zak")
net.place("fronta", (6.5, -10.4), label="Fronta", label_pos="below")
net.immediate("obsaz", (8, -10.4))
net.place("obsluha", (9.5, -10.4))
net.timed("t_obsl", (11, -10.4), "1–2 min", param_pos="below")
net.chain("t_zak", "fronta", "obsaz", "obsluha", "t_obsl")
net.arc("prac", "obsaz")
net.arc("t_obsl", "prac", out=90, into=315)
net.place("obslouzen", (13, -10.4))
net.arc("t_obsl", "obslouzen")
net.immediate("vydej", (14.5, -8.9), p=1, label="výdej", label_pos="above left",
              param_pos="above right")
net.immediate("bez", (14.5, -11.9), label="bez zásilky", label_pos="below")
net.arc("obslouzen", "vydej", via=[(13, -8.9)], corner=20)
net.arc("obslouzen", "bez", via=[(13, -11.9)], corner=20)
net.arc("uschovna", "vydej")
net.place("odchazi", (16.5, -10.4))
net.arc("vydej", "odchazi", via=[(16.5, -8.9)], corner=20)
net.arc("bez", "odchazi", via=[(16.5, -11.9)], corner=20)
net.immediate("odchod_k", (18, -10.4), exit=True, label="odchod", label_pos="below")
net.arc("odchazi", "odchod_k")

net.invariant({"vuz": 1, "naklada": 1, "rozhod": 1, "jede": 1, "u_zak": 1, "predava": 1,
               "nezast": 1, "navrat": 1, "vratil": 1, "vyklada": 1, "vyklada_z": 1}, 1)
net.invariant({"prac": 1, "naklada": 1, "vyklada": 1, "vyklada_z": 1, "obsluha": 1}, 3)
net.bound("ve_voze", 20)
